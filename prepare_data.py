def parse_objects_from_text(text_path):
    """Парсит текстовый файл и возвращает ВСЕ объекты"""
    objects = []
    current_category = None

    with open(text_path, 'r', encoding='utf-8') as f:
        lines = f.readlines()

    for line in lines:
        line = line.strip()
        if not line:
            continue

        # Заголовок категории (с двоеточием)
        if ':' in line:
            current_category = line.replace(':', '').strip()
            print(f"  Категория: {current_category}")
            continue

        # Если нет категории - пропускаем
        if not current_category:
            continue

        # Убираем табуляции и лишние пробелы
        line = re.sub(r'\s+', ' ', line).strip()

        # Определяем модификатор и базовое имя
        name = line
        base_name = line
        modifier = None

        # Проверяем известные паттерны модификаторов
        if line.endswith(' П'):
            name = line
            base_name = line[:-2].strip()
            modifier = 'П'
        elif line.endswith(' ОК'):
            name = line
            base_name = line[:-3].strip()
            modifier = 'ОК'
        elif line.endswith(' Н'):
            name = line
            base_name = line[:-2].strip()
            modifier = 'Н'
        elif line.endswith(' А'):
            name = line
            base_name = line[:-2].strip()
            modifier = 'А'
        elif ' (выше 2 м)' in line:
            name = line
            base_name = 'стены'
            modifier = 'выше 2 м'
        elif ' (до 2 м)' in line:
            name = line
            base_name = 'стены'
            modifier = 'до 2 м'
        elif ' (внешние)' in line:
            name = line
            base_name = 'окна'
            modifier = 'внешние'
        elif ' (внутрицеховые)' in line:
            name = line
            base_name = 'окна'
            modifier = 'внутрицеховые'
        elif ' (контактная поверхность)' in line:
            name = line
            base_name = 'демосистема'
            modifier = 'контактная поверхность'

        objects.append({
            "name": name,
            "base_name": base_name,
            "modifier": modifier,
            "category": current_category,
            "sort_priority": 0
        })

    return objects


def parse_excel_instructions(excel_path):
    """Парсит Excel и возвращает ВСЕ инструкции"""
    instructions = []

    wb = load_workbook(excel_path, data_only=True)
    ws = wb.active

    current_category = None

    for row in ws.iter_rows(min_row=1, values_only=True):
        if not any(row):
            continue

        object_name = str(row[0]).strip() if row[0] else ""

        # Заголовок категории
        if object_name.endswith(':'):
            current_category = object_name.replace(':', '').strip()
            continue

        # Пропускаем служебные строки
        if not object_name or object_name == "Объект обработки" or not current_category:
            continue

        # Создаем инструкцию
        instruction = {
            "object_name": object_name,
            "category": current_category,
            "cleaning_method": str(row[1]).strip() if len(row) > 1 and row[1] else "",
            "instruction_number": str(row[2]).strip() if len(row) > 2 and row[2] else "",
            "product_name": str(row[3]).strip() if len(row) > 3 and row[3] else "",
            "cleaning_technique": str(row[4]).strip() if len(row) > 4 and row[4] else "",
            "concentration": str(row[5]).strip() if len(row) > 5 and row[5] else "",
            "temperature": str(row[6]).strip() if len(row) > 6 and row[6] else "",
            "exposure_time": str(row[7]).strip() if len(row) > 7 and row[7] else "",
            "inventory": str(row[8]).strip() if len(row) > 8 and row[8] else "",
            "frequency": str(row[9]).strip() if len(row) > 9 and row[9] else "",
            "executor": str(row[10]).strip() if len(row) > 10 and row[10] else "",
            "control_method": str(row[11]).strip() if len(row) > 11 and row[11] else ""
        }

        instructions.append(instruction)

    return instructions


def match_instructions_to_objects(objects, excel_instructions):
    """
    Для каждого объекта из текстового файла:
    - ищем соответствующие инструкции в Excel по словарю MATCH_RULES
    - если есть - добавляем их
    - если нет - добавляем пустую инструкцию
    """

    # Индекс для быстрого поиска инструкций по категории
    excel_by_category = {}
    for instr in excel_instructions:
        cat = instr["category"]
        if cat not in excel_by_category:
            excel_by_category[cat] = []
        excel_by_category[cat].append(instr)

    result_instructions = []

    stats = {
        "total": len(objects),
        "with_instructions": 0,
        "without_instructions": 0
    }

    for obj in objects:
        obj_name = obj["name"]
        obj_category = obj["category"]

        found = False

        # Получаем правила для этого объекта
        rules = MATCH_RULES.get(obj_name, [])

        # Если правила есть, ищем по ним
        if rules:
            for rule in rules:
                # Ищем инструкции в нужной категории
                if obj_category in excel_by_category:
                    for instr in excel_by_category[obj_category]:
                        if rule in instr["object_name"]:
                            # Копируем и меняем object_name на наш
                            new_instr = instr.copy()
                            new_instr["object_name"] = obj_name
                            result_instructions.append(new_instr)
                            found = True

        # Специальный случай: "тележки" в двух категориях
        if obj_name == "тележки":
            # Ищем в обеих категориях
            for cat in ["Инвентарь, посуда и т.д.", "Моечный, уборочный инвентарь"]:
                if cat in excel_by_category:
                    for instr in excel_by_category[cat]:
                        if "тележки" in instr["object_name"].lower():
                            new_instr = instr.copy()
                            new_instr["object_name"] = obj_name
                            new_instr["category"] = obj_category  # меняем на нужную категорию
                            result_instructions.append(new_instr)
                            found = True

        if found:
            stats["with_instructions"] += 1
        else:
            # Нет инструкций - добавляем пустую
            empty_instr = {
                "object_name": obj_name,
                "category": obj_category,
                "cleaning_method": "",
                "instruction_number": "",
                "product_name": "",
                "cleaning_technique": "",
                "concentration": "",
                "temperature": "",
                "exposure_time": "",
                "inventory": "",
                "frequency": "",
                "executor": "",
                "control_method": ""
            }
            result_instructions.append(empty_instr)
            stats["without_instructions"] += 1

    return result_instructions, stats


